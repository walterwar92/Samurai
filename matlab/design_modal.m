function [K, eigs_closed] = design_modal(Ad, Bd, poles_cont, Ts)
% DESIGN_MODAL — модальный синтез (pole placement) для дискретной системы.
%
%   ИДЕЯ МЕТОДА (учебник §3.1):
%   Задаём ВРУЧНУЮ желаемые собственные значения замкнутой системы
%   (то есть «как мы хотим, чтобы система реагировала») и подбираем
%   матрицу обратной связи K такую, что:
%
%       eig(Ad − Bd·K) = {λ_1^уст, λ_2^уст, ..., λ_n^уст}
%
%   КОГДА ИСПОЛЬЗОВАТЬ ВМЕСТО ЛКР?
%   Когда есть конкретные требования к динамике (например, «время
%   переходного процесса не более 1.5 с, без перерегулирования»),
%   которые проще выразить в терминах полюсов, чем подобрать веса Q, R.
%
%   ПРОЦЕДУРА (учебник §3.1.2 — приведение к канонической форме Фробениуса):
%     1. Строим вспомогательную матрицу T из коэффициентов χ_n(λ).
%     2. Преобразование подобия Q = S_y · T приводит (A, B) к форме Фробениуса.
%     3. Из коэффициентов желаемого полинома строим вектор a_уст.
%     4. K = (Q')^(-1) · (a − a_уст)   ← формула 3.4 учебника
%
%   В MATLAB вся эта процедура завёрнута в функцию place(), которая
%   к тому же поддерживает многомерный вход (r > 1) через алгоритм
%   Tits-Yang. Поэтому мы используем её.
%
%   ОТОБРАЖЕНИЕ НЕПРЕРЫВНЫХ ПОЛЮСОВ В ДИСКРЕТНЫЕ:
%   Пользователь задаёт желаемые НЕПРЕРЫВНЫЕ полюса poles_cont
%   (легче выбирать: λ < 0 для устойчивости). Перед вызовом place()
%   их нужно перевести в дискретные через отображение
%       λ_дискр = exp(λ_непр · Ts)   ← формула в §3.1.3 учебника

  n = size(Ad, 1);

  % ── Шаг 1: непрерывные → дискретные полюса ────────────────────
  poles_disc = exp(poles_cont(:) * Ts);

  % ── Шаг 2: вызов алгоритма Tits-Yang ──────────────────────────
  % place() требует, чтобы среди желаемых полюсов не было слишком близких
  % дубликатов; для нашей задачи это всегда выполнено.
  K = place(Ad, Bd, poles_disc);

  % ── ПРОВЕРКА: достигнуты ли запрошенные полюса? ───────────────
  Acl = Ad - Bd * K;
  eigs_closed = eig(Acl);

  fprintf('Сводка модального синтеза:\n');
  fprintf('  Желаемые λ (дискр):  %s\n', mat2str(poles_disc, 4));
  fprintf('  Полученные λ:        %s\n', mat2str(eigs_closed, 4));
  fprintf('  K (2×5) — коэффициент обратной связи:\n');     disp(K);

  % ── ПРЕДУПРЕЖДЕНИЕ при положительных полюсах ──────────────────
  % Это «защита от дурака»: если пользователь вписал положительные
  % полюса в samurai_params (для демонстрации неустойчивости), хотя бы
  % выведем сообщение в лог.
  if any(real(poles_cont) > 0)
    warning('design_modal:unstable', ...
            ['ВНИМАНИЕ: Среди желаемых полюсов есть положительные — ', ...
             'замкнутая система БУДЕТ НЕУСТОЙЧИВА! ', ...
             'Это допустимо только для демонстрации в симуляторе.']);
  end
end
