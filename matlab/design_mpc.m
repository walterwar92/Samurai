function mpc = design_mpc(Ad, Bd, Q, R, Pf, N)
% DESIGN_MPC — построение MPC-регулятора (Model Predictive Control).
%
%   ЧЕМ MPC ЛУЧШЕ ЛКР?
%   ЛКР даёт оптимальный регулятор для НЕОГРАНИЧЕННОЙ задачи. Но реальный
%   робот имеет жёсткие физические лимиты:
%       |u_v|     ≤ 0.30 м/с      (max_linear)
%       |u_omega| ≤ 2.0  рад/с    (max_angular)
%   Если ЛКР рассчитал u_v = 0.5 м/с, актуатор насытит на 0.30 — и
%   оптимальность теряется (anti-windup проблемы, скачки).
%
%   MPC ЯВНО УЧИТЫВАЕТ ОГРАНИЧЕНИЯ:
%   На каждом шаге решает оптимизационную задачу с ограничениями
%   на горизонте N шагов вперёд:
%
%       min_U    Σ_{i=0..N-1}(x_i'Qx_i + u_i'Ru_i) + x_N' Pf x_N
%       при       x_{i+1} = Ad·x_i + Bd·u_i,
%                 u_min ≤ u_i ≤ u_max
%
%   где U = [u_0; u_1; ...; u_{N-1}] — последовательность управлений.
%   Применяется ТОЛЬКО первое u_0, затем горизонт сдвигается
%   («receding horizon» — принцип сдвигаемого горизонта).
%
%   ПРИНЦИП РЕАЛИЗАЦИИ — СВЕДЕНИЕ К QP:
%   Развёртываем динамику итеративно (lifting) и подставляем в критерий.
%   Получаем стандартную квадратичную задачу:
%
%       min_U   ½ U' H U + (f_mat · x_0)' U,    при  G U ≤ g
%
%   Матрица H — КОНСТАНТНА (не зависит от текущего состояния),
%   её можно вычислить ОДИН РАЗ (offline). Вектор f меняется
%   на каждом шаге пропорционально x_0.
%
%   ТЕРМИНАЛЬНЫЙ ШТРАФ Pf:
%   Чтобы гарантировать устойчивость замкнутой системы при конечном
%   горизонте N, выбираем Pf = решение DARE (теорема об устойчивости MPC,
%   Mayne et al. 2000). Это реализовано в main.m: Pf = P_inf от ЛКР.
%
%   ВЫХОД (struct mpc):
%     mpc.N        — горизонт прогноза
%     mpc.Phi      — лифтинг-матрица (n·N × n) — связь x_0 → x_1...x_N
%     mpc.Gamma    — лифтинг-матрица (n·N × r·N) — связь U → x_1...x_N
%     mpc.H        — гессиан QP (r·N × r·N), симметричная, поло-опр.
%     mpc.f_mat    — линейный коэффициент QP (f = f_mat · x_0)
%     mpc.K_first  — ЯВНЫЙ коэффициент для первого управления
%                    (без активных ограничений) u_0 = −K_first·x_0
%     mpc.Q_bar    — блочно-диагональная Q (для удобства Python-стороны)
%     mpc.R_bar    — блочно-диагональная R

  n = size(Ad, 1);
  r = size(Bd, 2);

  % ── ШАГ 1: построение Phi и Gamma (развёртка динамики) ────────
  % По итеративной подстановке x_{i+1} = Ad·x_i + Bd·u_i:
  %   x_1 = Ad·x_0 + Bd·u_0
  %   x_2 = Ad²·x_0 + Ad·Bd·u_0 + Bd·u_1
  %   x_3 = Ad³·x_0 + Ad²·Bd·u_0 + Ad·Bd·u_1 + Bd·u_2
  %   ...
  % Это можно записать как X = Phi·x_0 + Gamma·U.
  Phi   = zeros(n*N, n);
  Gamma = zeros(n*N, r*N);
  Apow  = eye(n);                      % будем накапливать степени Ad
  for i = 1:N
    Apow = Ad * Apow;                  % теперь Apow = Ad^i
    Phi((i-1)*n + (1:n), :) = Apow;
    for j = 1:i
      block = Ad^(i-j) * Bd;           % степень от 0 до i-1
      Gamma((i-1)*n + (1:n), (j-1)*r + (1:r)) = block;
    end
  end

  % ── ШАГ 2: блочно-диагональные веса ───────────────────────────
  % Q применяется к каждому промежуточному состоянию x_1, ..., x_{N-1};
  % Pf применяется к терминальному состоянию x_N (этот штраф «сшивает»
  % конечный горизонт с бесконечным).
  Q_bar = kron(eye(N-1), Q);           % блок-диаг. Q (повторённая N-1 раз)
  Q_bar = blkdiag(Q_bar, Pf);          % добавляем Pf в конец
  R_bar = kron(eye(N), R);             % блок-диаг. R (повторённая N раз)

  % ── ШАГ 3: построение QP-матриц ───────────────────────────────
  % J = X' Q_bar X + U' R_bar U
  %   = (Phi·x0 + Gamma·U)' Q_bar (Phi·x0 + Gamma·U) + U' R_bar U
  %   = ½ U' [2·(Gamma' Q_bar Gamma + R_bar)] U
  %     + (2·Gamma' Q_bar Phi · x0)' U + const(x0)
  %     ────────────────────────────────────────────
  %        H                              f
  H     = 2 * (Gamma' * Q_bar * Gamma + R_bar);
  f_mat = 2 * Gamma' * Q_bar * Phi;

  % Симметризация (числовая гигиена) — даже если в теории H симметрична,
  % после флоат-арифметики может появиться |H − H'| ≈ 1e-15.
  H = 0.5 * (H + H');

  % ── ШАГ 4: ЯВНОЕ решение для случая БЕЗ активных ограничений ──
  % min_U  ½ U'HU + (f_mat·x0)' U  →  ∇_U J = HU + f_mat·x0 = 0
  %                                    →  U* = −H^(-1) · f_mat · x0
  % Берём первые r строк (это и есть u_0):
  %     u_0* = (−H^(-1) · f_mat)[1:r, :] · x0  =  −K_full[1:r, :] · x0
  %
  % СОГЛАШЕНИЕ ЗНАКОВ: используем LQR-конвенцию, где u = −K·x
  % (положительная K). Поэтому:
  %     K_first = (H^(-1) · f_mat)[1:r, :]   ← положительная
  %     u_0     = −K_first · x_0             ← применяется со знаком минус
  % Это согласовано с simulate_closed_loop.m и Python-кодом.
  K_full  = H \ f_mat;                  % H^(-1) · f_mat, размер (r·N) × n
  K_first = K_full(1:r, :);             % первые r строк → r × n

  % ── Упаковка результатов ──────────────────────────────────────
  mpc.N        = N;
  mpc.Phi      = Phi;
  mpc.Gamma    = Gamma;
  mpc.H        = H;
  mpc.f_mat    = f_mat;
  mpc.K_first  = K_first;
  mpc.Q_bar    = Q_bar;
  mpc.R_bar    = R_bar;

  % ── Проверка устойчивости замкнутой системы с K_first ─────────
  % При больших N и Pf = решение DARE, K_first → K_LQR, и замкнутая
  % система устойчива по построению. Проверим явно.
  Acl = Ad - Bd * K_first;
  eigs_cl = eig(Acl);
  fprintf('Сводка MPC-синтеза:\n');
  fprintf('  Горизонт N = %d, размер QP: %d переменных, %d×%d матрица H\n', ...
          N, r*N, r*N, r*N);
  fprintf('  K_first (%d×%d) — явный коэффициент первого шага:\n', ...
          size(K_first));
  disp(K_first);
  fprintf('  |λ| замкнутой системы (без ограничений): %s\n', ...
          mat2str(abs(eigs_cl), 4));
end
