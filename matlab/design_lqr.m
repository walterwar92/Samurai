function [K, P, eigs_closed] = design_lqr(Ad, Bd, Q, R)
% DESIGN_LQR — синтез линейно-квадратичного регулятора (ЛКР) для дискретной системы.
%
%   ИДЕЯ ЛКР (учебник §3.3):
%   В отличие от модального синтеза, где мы ВРУЧНУЮ выбираем полюса замкнутой
%   системы, ЛКР АВТОМАТИЧЕСКИ находит оптимальный регулятор, минимизирующий
%   интегральный критерий качества:
%
%       J = Σ_{k=0..∞} (x_k' Q x_k + u_k' R u_k)   ← дискретный аналог формулы (3.9)
%
%   где:
%       Q ≽ 0 — штраф за отклонение состояния (точность)
%       R ≻ 0 — штраф за затраты управления (энергия/износ)
%
%   ОПТИМАЛЬНОЕ УПРАВЛЕНИЕ ИМЕЕТ ЛИНЕЙНУЮ ФОРМУ (формула 3.10):
%       u_k* = -K · x_k,   K = (R + B'PB)^(-1) · B'PA
%
%   где P — симметричная положительно определённая матрица, удовлетворяющая
%   ДИСКРЕТНОМУ алгебраическому уравнению Риккати (DARE, формула 3.11):
%
%       A' P A − P − A' P B (R + B' P B)^(-1) B' P A + Q = 0
%
%   УСЛОВИЯ СУЩЕСТВОВАНИЯ единственного P > 0 (учебник §3.3):
%     1) пара (A,B) полностью управляема;
%     2) R > 0 (положительно определена);
%     3) Q > 0  ИЛИ  Q = H'H при наблюдаемой паре (A',H').
%
%   ВЫХОДЫ:
%     K           — оптимальный коэффициент обратной связи (r × n)
%     P           — решение DARE (n × n, симметричная и поло-опр.)
%     eigs_closed — собственные значения замкнутой системы Ad - Bd·K
%                   (все должны быть внутри единичного круга)

  % MATLAB предоставляет TWO-в-одном:
  %   • idare — современная функция (R2018b+), численно стабильнее
  %   • dare  — legacy, доступна везде
  % Используем idare если есть.
  if exist('idare', 'file') == 2
    [P, K_pos, ~] = idare(Ad, Bd, Q, R);
    K = K_pos;       % idare возвращает K такой, что u = -K·x
  else
    [P, ~, K_pos] = dare(Ad, Bd, Q, R);
    K = K_pos;
  end

  % ── ПРОВЕРКА: замкнутая система устойчива? ────────────────────
  % По теореме об устойчивости ЛКР, если выполнены условия существования,
  % то замкнутая система Ad − Bd·K автоматически устойчива (все λ внутри
  % единичного круга). Проверим явно — на случай численных проблем.
  Acl = Ad - Bd * K;
  eigs_closed = eig(Acl);
  if any(abs(eigs_closed) >= 1)
    warning('design_lqr:unstable', ...
            'ВНИМАНИЕ: Собственные значения замкнутой системы вне единичного круга!');
  end

  % ── Распечатка результатов для логов ──────────────────────────
  fprintf('Сводка ЛКР-синтеза:\n');
  fprintf('  K (2×5) — коэффициент обратной связи u = −K·x:\n');     disp(K);
  fprintf('  |λ| замкнутой системы: %s\n', mat2str(abs(eigs_closed), 4));
  fprintf('  (все должны быть < 1 для устойчивости)\n');
end
