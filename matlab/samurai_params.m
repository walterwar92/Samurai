function p = samurai_params()
% SAMURAI_PARAMS — физические параметры объекта и веса критерия качества.
%
%   Возвращает struct со ВСЕМИ настройками, которые нужны для синтеза
%   регулятора. Это единая «точка правды»: меняешь здесь — main.m
%   пересчитывает матрицы и пишет их в ../config.yaml в раздел `control:`.
%
%   После запуска main.m робот при следующем старте подхватит новые
%   коэффициенты — перекомпиляции Python-кода НЕ требуется.
%
%   Соответствие учебнику Козлов В.Н. и др. «ТАУ» (СПбГПУ, 2008):
%     • v0       — опорная скорость для линеаризации (см. §1.1, формула 1.2)
%     • tau_v/w  — постоянные времени апериодических звеньев моторов
%     • Q, R     — веса в критерии J = ∫(x'Qx + u'Ru)dt (см. §3.3, формула 3.9)
%     • poles    — желаемые корни χ_n^уст(λ) для модального синтеза (§3.1.3)

  % ── Параметры объекта (физика робота) ─────────────────────────
  % v0 — это та скорость, ВОКРУГ КОТОРОЙ мы линеаризуем нелинейную
  % модель. Робот хорошо описывается линейной моделью только в малой
  % окрестности этой точки. Для движения «вперёд по умолчанию»
  % разумно взять середину диапазона: 0.20 м/с (= profile "normal").
  p.v0       = 0.20;     % м/с    — опорная линейная скорость

  % tau_v и tau_w — постоянные времени апериодических звеньев первого
  % порядка для моторов. Физически: команда u_v не отрабатывается мгновенно —
  % реальная скорость v(t) подходит к u_v экспоненциально с временем tau_v.
  % Значения подобраны экспериментально (см. tests/test_motor_lag.py).
  % Если у вас другое шасси (тяжелее/легче) — измените эти числа.
  p.tau_v    = 0.15;     % с      — постоянная мотора (linear)
  p.tau_w    = 0.10;     % с      — постоянная мотора (angular)

  % Ширина базы — расстояние между гусеницами. Используется в
  % дифференциальной кинематике (см. формула 1.1 в latex_doc).
  % В синтезе регулятора напрямую НЕ используется (только в физическом
  % моделировании); хранится здесь для справки.
  p.B_base   = 0.17;     % м      — ширина базы (info)

  % Период дискретизации. ВАЖНО: должен совпадать с частотой цикла
  % motor_node (timer 0.05 с = 20 Гц), иначе K-матрицы рассчитаны
  % для одной частоты, а применяются на другой → деградация устойчивости.
  p.Ts       = 0.05;     % с      — период дискретизации (= 1 / 20 Гц)

  % ── Веса критерия качества J = Σ(x'Qx + u'Ru) ─────────────────
  % Порядок состояния: x = [px, py, theta, v, omega]'
  %
  % Большие Q[i,i] → регулятор СИЛЬНЕЕ штрафует отклонение i-й
  %                  координаты → точнее её держит, но реакция резче.
  % Большие R[j,j] → регулятор СИЛЬНЕЕ штрафует затраты на j-е
  %                  управление → бережёт управление, реакция плавнее.
  %
  % Для робота: точность позиции (px, py) и курса (theta) важнее точности
  % внутренних скоростей (v, omega), поэтому Q[1:3] большие, Q[4:5] малые.
  % R = I — равномерный базовый штраф управлений.
  p.Q        = diag([10, 10, 5, 1, 1]);
  p.R        = diag([1, 1]);

  % ── Физические ограничения управления ─────────────────────────
  % Эти лимиты — фактический потолок моторов робота.
  % MPC использует их в активной форме (constraints), LQR — только
  % для финального clip на выходе.
  p.u_min    = [-0.30; -2.0];   % [м/с; рад/с]
  p.u_max    = [+0.30; +2.0];

  % ── MPC ───────────────────────────────────────────────────────
  % N — число шагов прогноза.
  %   Маленький N (≤5)  → быстро, но не видит дальше → возможны рывки.
  %   Большой   N (≥30) → плавно и оптимально, но дороже по CPU.
  %   Для Pi 4 (Cortex-A72) безопасно держать N=10..20.
  % При N → ∞ и Pf = решение Риккати, MPC сходится к LQR.
  p.N        = 10;

  % ── Модальный регулятор (pole placement) ──────────────────────
  % Желаемые НЕПРЕРЫВНЫЕ полюса замкнутой системы λ_i^уст.
  % Условие устойчивости (учебник §3.1): Re(λ_i^уст) < 0 для всех i.
  % Длительность переходного процесса t_n ≈ 3 / min|Re(λ_i)|.
  %
  % Текущий выбор: спектр от -2 до -10 → характерное время 0.1...0.5 с,
  % t_n ≈ 1.5 с. Это ровно то, что просит учебник в формуле 3.0.
  %
  % ⚠ ХОТИТЕ ОШИБОЧНОЕ ПОВЕДЕНИЕ для демонстрации?
  %   Поставьте поположительнее (например +1.0) — замкнутая система
  %   станет неустойчивой и робот «убежит». Безопасно ТОЛЬКО в симуляторе.
  p.poles_continuous = [-2; -3; -4; -8; -10];

  % Во сколько раз полюса наблюдателя быстрее полюсов регулятора.
  % Стандартная рекомендация (учебник §3.4.2): 5...10.
  % Меньше → наблюдатель не успевает «догонять» состояние;
  % больше → наблюдатель усиливает шум измерений.
  p.observer_speedup = 5.0;

  % ── МПС — параметры канонической модели [s, v, theta, omega, e_int] ──
  % Отдельная подсистема: модуль курсовой «проехать D метров вперёд».
  % НЕ путать с legacy-моделью [px, py, theta, v, omega] выше.
  % tau_v / tau_w — те же физические постоянные моторов (тот же робот).
  p.mps.tau_v = p.tau_v;          % с — постоянная linear-мотора
  p.mps.tau_w = p.tau_w;          % с — постоянная angular-мотора
  p.mps.Ts    = 0.02;             % с — период дискретизации МПС (50 Гц)

  % Веса критерия J для ПОРЯДКА [s, v, theta, omega, e_int] — НЕ совпадает
  % с порядком legacy-модели, хотя численно те же значения.
  p.mps.Q     = diag([10, 10, 5, 1, 1]);
  p.mps.R     = diag([1, 1]);
  p.mps.N     = 10;               % горизонт MPC
  p.mps.u_min = [-0.30; -2.0];    % [м/с; рад/с]
  p.mps.u_max = [+0.30; +2.0];
end
