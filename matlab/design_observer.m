function [L, eigs_obs] = design_observer(Ad, C, K_eigs, Ts, speedup)
% DESIGN_OBSERVER — синтез полноразмерного наблюдателя Луенбергера.
%
%   ЗАЧЕМ НУЖЕН НАБЛЮДАТЕЛЬ?
%   Регулятор u = −K·x требует ПОЛНОГО вектора состояния x. На реальном
%   роботе мы измеряем только y = C·x (вектор сенсоров); внутренние
%   скорости v, omega и т.д. напрямую не наблюдаемы. Наблюдатель ВОССТАНАВЛИВАЕТ
%   x по доступным y и известной модели.
%
%   ПРИНЦИП РАБОТЫ (учебник §3.4.1, формула 3.18):
%       d̂x/dt = A·x̂ + B·u + L·(y − C·x̂)
%       ────────────────  ────────────────
%       прогноз модели    коррекция по ошибке
%
%   ОШИБКА НАБЛЮДЕНИЯ e = x − x̂ удовлетворяет:
%       de/dt = (A − L·C) · e        ← формула 3.18
%
%   То есть e → 0 при t → ∞ ⇔ матрица (A − L·C) устойчива.
%
%   ВЫБОР L — ДУАЛЬНАЯ ЗАДАЧА К ВЫБОРУ K (учебник §3.4.2):
%   Сравним:
%       Регулятор:  выбираем K так, чтобы (A − B·K) имела заданные λ.
%       Наблюдатель: выбираем L так, чтобы (A − L·C) имела заданные λ.
%   Заметим: eig(A − L·C) = eig(A' − C'·L'), то есть проблема ИДЕНТИЧНА
%   pole-placement для дуальной системы (A', C'). Поэтому:
%       L' = place(A', C', желаемые_λ)
%
%   КАК ВЫБИРАТЬ ПОЛЮСА НАБЛЮДАТЕЛЯ?
%   Стандартная практика (учебник §3.4.2): полюса наблюдателя в speedup
%   раз БЫСТРЕЕ полюсов регулятора. Тогда наблюдатель «догоняет»
%   реальное состояние быстрее, чем регулятор реагирует, и принцип
%   разделения работает (формула 3.23):
%       eig(замкнутая) = eig(A − B·K) ∪ eig(A − L·C)
%
%   ВХОДЫ:
%     Ad, C   — дискретная модель объекта
%     K_eigs  — собственные значения (Ad − Bd·K) от ЛКР/модального синтеза
%     Ts      — период дискретизации
%     speedup — во сколько раз наблюдатель быстрее регулятора (типично 5...10)

  n = size(Ad, 1);

  % ── Шаг 1: дискр. полюса регулятора → непрерывные ─────────────
  % Логарифм комплексного числа существует, и для устойчивых дискр. полюсов
  % (|λ| < 1) даёт log(λ) с Re < 0 → корректные непрерывные полюса.
  lam_reg_cont = log(K_eigs) / Ts;

  % ── Шаг 2: ускоряем в speedup раз (в непрерывном времени) ─────
  lam_obs_cont = speedup * lam_reg_cont;

  % ── Шаг 3: непрерывные → дискретные ───────────────────────────
  lam_obs_disc = exp(lam_obs_cont * Ts);

  % ── Шаг 4: насыщение слишком малых полюсов ────────────────────
  % Если speedup большой, exp(speedup·log(λ)·Ts) может оказаться
  % очень близко к 0, и numpy/MATLAB могут «потерять» полюс численно.
  % Поэтому ограничиваем |λ| ≥ 1e-3.
  for i = 1:length(lam_obs_disc)
    if abs(lam_obs_disc(i)) < 1e-3
      lam_obs_disc(i) = sign(real(lam_obs_disc(i))) * 1e-3;
    end
  end

  % ── ПРОВЕРКА: объект полностью наблюдаем? ─────────────────────
  % Учебник §3.4.1, формула 3.17: rank(S_n) = n,
  % где S_n = [C'; A'C'; (A')²C'; ...; (A')^(n-1) C'].
  % Если ранг < n — некоторые координаты принципиально невосстановимы.
  Sn = obsv(Ad, C);
  if rank(Sn) < n
    error('design_observer:notObservable', ...
          'Пара (A,C) не наблюдаема: rank(S_n)=%d, n=%d', rank(Sn), n);
  end

  % ── Шаг 5: pole-placement на дуальной системе ─────────────────
  % place(A', C', λ_желаемые) возвращает K_dual такую, что
  % eig(A' − C'·K_dual) = λ_желаемые. Тогда L = K_dual'.
  L = place(Ad', C', lam_obs_disc)';

  % ── Финальная проверка ────────────────────────────────────────
  Aobs = Ad - L * C;
  eigs_obs = eig(Aobs);

  fprintf('Сводка синтеза наблюдателя:\n');
  fprintf('  Желаемые λ_obs (дискр): %s\n', mat2str(lam_obs_disc, 4));
  fprintf('  Полученные λ_obs:       %s\n', mat2str(eigs_obs, 4));
  fprintf('  (наблюдатель в %.1f×Х быстрее регулятора)\n', speedup);
end
