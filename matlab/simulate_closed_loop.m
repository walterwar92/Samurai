function simulate_closed_loop(Ad, Bd, K, x0, T, u_min, u_max, label)
% SIMULATE_CLOSED_LOOP — симуляция замкнутой системы x_{k+1} = (Ad − Bd·K)·x_k.
%
%   ЗАЧЕМ:
%   После синтеза регулятора (ЛКР, модального или MPC) хочется
%   ПОСМОТРЕТЬ, как замкнутая система ведёт себя на ступенчатом
%   возмущении. Это «проверка глазами» — графики переходных процессов
%   сравниваются с тем, что показано в учебнике (рис. 25-32).
%
%   ЧТО ИМИТИРУЕТСЯ:
%   На каждом шаге k:
%     1. Контроллер выдаёт u_k = −K·x_k.
%     2. u_k насыщается до [u_min, u_max] (модель насыщения актуатора).
%     3. Объект делает шаг: x_{k+1} = Ad·x_k + Bd·u_k.
%   Это та же логика, что и в Python (clip-режим MPC), поэтому графики
%   из MATLAB должны совпадать с поведением реального робота.
%
%   ВХОДЫ (с разумными значениями по умолчанию):
%     Ad, Bd  — дискретная модель
%     K       — статический коэффициент обратной связи (LQR-конвенция: u = −K·x)
%     x0      — начальное отклонение от опорной точки
%               (по умолчанию: 1 м назад, 1 м вбок, 0.5 рад крен)
%     T       — число шагов симуляции (по умолчанию 200 = 10 с при Ts=0.05)
%     u_min/max — лимиты управления (по умолчанию off — нет насыщения)
%     label   — заголовок графика
%
%   НА ВЫХОДЕ:
%     Окно с двумя графиками — состояния и управления во времени.

  if nargin < 4 || isempty(x0),   x0    = [1; 1; 0.5; 0; 0]; end
  if nargin < 5 || isempty(T),    T     = 200;               end
  if nargin < 6, u_min = [];                                  end
  if nargin < 7, u_max = [];                                  end
  if nargin < 8, label = 'Замкнутая система — переходный процесс'; end

  n = size(Ad, 1);
  r = size(Bd, 2);

  % ── Преаллокация массивов траекторий ──────────────────────────
  X = zeros(n, T+1);   X(:, 1) = x0;    % T+1 столбцов — включая x_0
  U = zeros(r, T);                       % T столбцов — u_0 ... u_{T-1}

  % ── Основной цикл симуляции ───────────────────────────────────
  for k = 1:T
    % LQR-конвенция: положительная K, применяется со знаком минус.
    u = -K * X(:, k);

    % Насыщение управления — имитируем физический лимит актуатора.
    if ~isempty(u_min), u = max(u, u_min); end
    if ~isempty(u_max), u = min(u, u_max); end
    U(:, k)   = u;

    % Дискретный шаг объекта.
    X(:, k+1) = Ad * X(:, k) + Bd * u;
  end

  % ── Построение графиков ───────────────────────────────────────
  % Предполагаем Ts = 0.05 для оси времени; если нужна другая Ts,
  % график лишь сместится по горизонтальной оси (значения корректны).
  t = (0:T) * 0.05;
  figure('Name', label);

  % Верхний график: компоненты состояния.
  subplot(2, 1, 1);
  plot(t, X', 'LineWidth', 1.2); grid on;
  ylabel('Состояние x_k');
  legend({'p_x (м)', 'p_y (м)', '\theta (рад)', 'v (м/с)', '\omega (рад/с)'}, ...
         'Location', 'best');
  title(label);

  % Нижний график: команды управления.
  % stairs() — ступенчатое отображение, корректно для дискретного управления.
  subplot(2, 1, 2);
  stairs(t(1:end-1), U', 'LineWidth', 1.2); grid on;
  ylabel('Управление u_k');
  xlabel('Время t, с');
  legend({'u_v (м/с)', 'u_\omega (рад/с)'}, 'Location', 'best');
end
