function [Ad, Bd] = discretize_samurai(A, B, Ts)
% DISCRETIZE_SAMURAI — точная дискретизация ZOH через матричную экспоненту.
%
%   ЗАЧЕМ ЭТО НУЖНО:
%   Регулятор работает в ДИСКРЕТНОМ времени (на каждом шаге цикла
%   motor_node @ 20 Гц). Чтобы корректно синтезировать дискретный регулятор,
%   нужна дискретная модель объекта:
%       x_{k+1} = Ad · x_k + Bd · u_k.
%
%   МЕТОД ZOH (Zero-Order Hold):
%   Предполагаем, что управление между сэмплами держится ПОСТОЯННЫМ
%   (как и реализуется в коде: u_k подаётся в driver и не меняется
%   до следующего тика). Это даёт ТОЧНОЕ соответствие между непрерывной
%   и дискретной моделями (без приближений типа Эйлера).
%
%   ФОРМУЛА (учебник §1.5):
%       Ad = exp(A·Ts),
%       Bd = ∫₀^Ts exp(A·τ) dτ · B.
%
%   ХАК ДЛЯ ОДНОВРЕМЕННОГО ВЫЧИСЛЕНИЯ:
%   Заметим, что блочная матричная экспонента
%       exp([A B; 0 0] · Ts)  =  [Ad Bd; 0 I],
%   то есть и Ad, и Bd получаются одним вызовом expm(). Это и численно
%   устойчиво, и синтаксически просто.

  n = size(A, 1);
  r = size(B, 2);

  % Собираем блочную матрицу размера (n+r)×(n+r) и берём от неё
  % матричную экспоненту. Внутри expm() — алгоритм Padé с масштабированием
  % (scale-and-square), численно устойчивый для нашего размера.
  M = expm([A, B; zeros(r, n + r)] * Ts);

  % Извлекаем подблоки.
  Ad = M(1:n, 1:n);                   % верхне-левый блок n×n
  Bd = M(1:n, n+1:n+r);               % верхне-правый блок n×r
  % Нижний блок [0 | I] нам не нужен.

  % ── ПРОВЕРКА: соответствие собственных значений ────────────────
  % По учебнику §3.1.3, при ZOH-дискретизации непрерывные
  % собственные значения отображаются в дискретные по правилу:
  %     λ_дискр = exp(λ_непр · Ts)
  % Если что-то рассыпалось при численном решении expm — выдадим warning.
  lam_cont = eig(A);
  lam_disc = eig(Ad);
  for i = 1:length(lam_cont)
    expected = exp(lam_cont(i) * Ts);
    [~, j] = min(abs(lam_disc - expected));
    if abs(lam_disc(j) - expected) > 1e-6
      warning('Несовпадение λ непрерывной/дискретной систем: %.4g vs %.4g', ...
              lam_disc(j), expected);
    end
  end
end
